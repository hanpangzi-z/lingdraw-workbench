const enToZh = new Map<string, string>();
for (const [zh, en] of translations) if (!enToZh.has(en)) enToZh.set(en, zh);

export function isEnglishPptLanguage(language: string) {
  return language.toLowerCase().startsWith("en");
}

export interface PptLocalizedValueState {
  source: string;
  lastApplied: string;
}

export function resolvePptLocalizedValue(current: string, language: string, previous?: PptLocalizedValueState) {
  const state = !previous || current !== previous.lastApplied
    ? { source: current, lastApplied: current }
    : previous;
  const value = isEnglishPptLanguage(language) ? translatePptText(state.source, language) : state.source;
  return { value, state: { source: state.source, lastApplied: value } };
}

